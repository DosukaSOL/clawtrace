            '.subtitle { color: #64748b; margin-top: 4px; }',
            '.meta { font-size: 0.8rem; color: #94a3b8; margin-top: 8px; }',
            'h2 { font-size: 1.4rem; color: #1e293b; margin: 24px 0 12px; padding-bottom: 8px; border-bottom: 1px solid #e2e8f0; }',
