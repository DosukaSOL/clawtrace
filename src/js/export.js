            '.warn-critical { background: rgba(220,38,38,0.08); border-left: 3px solid #dc2626; }',
            '.warn-error { background: rgba(239,68,68,0.08); border-left: 3px solid #ef4444; }',
            '.warn-warning { background: rgba(245,158,11,0.08); border-left: 3px solid #f59e0b; }',
